import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import test from "node:test";
import sharp from "sharp";
import { inspectImageFile } from "../image-cli.js";
import { parseContentDocument } from "../content-audit.js";
import { updateImageMedia } from "../image-media-cli.js";

test("dynamic WebP and GIF are recognized from frames and backfill preserves wording, sources and image bytes", async t => {
  const root = await mkdtemp(path.join(os.tmpdir(), "xgif-media-"));
  t.after(() => rm(root, { recursive: true, force: true }));
  for (const folder of ["site/public/images", "site/src/content/images", "workflow"]) await mkdir(path.join(root, folder), { recursive: true });
  const pixels = Buffer.alloc(200 * 400 * 3);
  for (let i = 0; i < 200 * 400; i++) pixels[i * 3 + (i < 200 * 200 ? 0 : 2)] = 255;
  const animated = await sharp(pixels, { raw: { width: 200, height: 400, channels: 3, pageHeight: 200 } }).webp({ delay: [100, 100], loop: 0 }).toBuffer();
  const still = await sharp({ create: { width: 200, height: 200, channels: 3, background: "red" } }).gif().toBuffer();
  const hash = b => createHash("sha256").update(b).digest("hex");
  await writeFile(path.join(root, "site/public/images/moving.webp"), animated);
  await writeFile(path.join(root, "site/public/images/still.gif"), still);
  assert.equal((await inspectImageFile(path.join(root, "site/public/images/moving.webp"))).animated, true);
  assert.equal((await inspectImageFile(path.join(root, "site/public/images/still.gif"))).animated, false);
  const members = [{ src: "/images/still.gif", altText: "原有标点，保持！" }, { src: "/images/moving.webp" }];
  const original = `---\ncontentId: "20261116-test"\ntitle: "原标题不动"\nsource: "原来源"\nimage: "${members[0].src}"\nimages: ${JSON.stringify(members)}\n---\n\n原文内容。\n`;
  const file = path.join(root, "site/src/content/images/20261116-test.md");
  await writeFile(file, original);
  assert.equal((await updateImageMedia({ repoRoot: root })).mode, "dry-run");
  assert.equal(await readFile(file, "utf8"), original);
  const report = await updateImageMedia({ repoRoot: root, apply: true });
  assert.equal(report.checkedMembers, 2); assert.equal(report.animatedMembers, 1);
  const changed = await readFile(file, "utf8");
  const data = parseContentDocument(changed).data;
  assert.deepEqual(data.images, members.map((member, i) => ({ ...member, animated: i === 1 })));
  assert.equal(changed.split("\n---\n")[1], original.split("\n---\n")[1]);
  assert.equal(data.title, "原标题不动"); assert.equal(data.source, "原来源");
  assert.equal(hash(await readFile(path.join(root, "site/public/images/moving.webp"))), hash(animated));
  assert.equal((await updateImageMedia({ repoRoot: root, apply: true })).changedFiles.length, 0);
  await rm(path.join(root, "site/public/images/moving.webp"));
  await assert.rejects(updateImageMedia({ repoRoot: root, apply: true }));
  assert.equal(await readFile(file, "utf8"), changed);
});
